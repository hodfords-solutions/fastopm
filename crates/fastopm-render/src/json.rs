//! JSON writers shared with the storage form; implemented in [`fastopm_core::json`].

pub(crate) use fastopm_core::json::*;

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::{Value, json};

    fn pretty(v: &Value) -> String {
        let mut out = Vec::new();
        write_value(&mut out, v, 0);
        String::from_utf8(out).unwrap()
    }

    #[test]
    fn number_forms() {
        let cases: &[(f64, &str)] = &[
            (1.0, "1"),
            (-0.0, "0"),
            (0.1, "0.1"),
            (1.5e-7, "1.5e-7"),
            (1e-6, "0.000001"),
            (1.234e-6, "0.000001234"),
            (1e21, "1e+21"),
            (1.5e21, "1.5e+21"),
            (1e20, "100000000000000000000"),
            (123456789012345680000.0, "123456789012345680000"),
            (9007199254740993.0, "9007199254740992"),
            (5e-324, "5e-324"),
            (1.7976931348623157e308, "1.7976931348623157e+308"),
            (-2.5, "-2.5"),
            (100.0, "100"),
        ];
        for (f, want) in cases {
            assert_eq!(js_number_string(*f), *want, "{f:e}");
        }
        assert_eq!(js_number_string(f64::NAN), "null");
    }

    #[test]
    fn integers_beyond_2_53_round_like_doubles() {
        assert_eq!(pretty(&json!(9007199254740993u64)), "9007199254740992");
        assert_eq!(pretty(&json!(u64::MAX)), "18446744073709552000");
        assert_eq!(pretty(&json!(i64::MIN)), "-9223372036854776000");
        assert_eq!(pretty(&json!(-42)), "-42");
    }

    #[test]
    fn string_escapes() {
        assert_eq!(
            pretty(&json!("a\"b\\c\u{8}\u{c}\n\r\t\u{1}\u{1f}\u{7f}\u{2028}é😀/")),
            "\"a\\\"b\\\\c\\b\\f\\n\\r\\t\\u0001\\u001f\u{7f}\u{2028}é😀/\""
        );
    }

    #[test]
    fn layout_and_key_order() {
        let v =
            json!({"b": 1, "10": [], "a": {}, "2": [1, {"x": null}], "01": true, "4294967295": 0});
        assert_eq!(
            pretty(&v),
            "{\n  \"2\": [\n    1,\n    {\n      \"x\": null\n    }\n  ],\n  \"10\": [],\n  \
             \"b\": 1,\n  \"a\": {},\n  \"01\": true,\n  \"4294967295\": 0\n}"
        );
    }

    #[test]
    fn array_index_rules() {
        assert_eq!(array_index("0"), Some(0));
        assert_eq!(array_index("4294967294"), Some(4294967294));
        assert_eq!(array_index("4294967295"), None);
        assert_eq!(array_index("00"), None);
        assert_eq!(array_index("-1"), None);
        assert_eq!(array_index(""), None);
        assert_eq!(array_index("1a"), None);
    }
    /// `Number#toString` and `JSON.stringify` vectors generated by `tests/fixtures/gen.cjs`.
    #[test]
    fn numbers_match_node() {
        let cases: Vec<(String, String)> =
            serde_json::from_str(include_str!("../tests/fixtures/expected/numbers.json")).unwrap();
        assert!(cases.len() > 5000);
        for (bits, want) in cases {
            let f = f64::from_bits(u64::from_str_radix(&bits, 16).unwrap());
            assert_eq!(js_number_string(f), want, "bits {bits}");
        }
    }

    #[test]
    fn strings_match_node() {
        let cases: Vec<(String, String)> =
            serde_json::from_str(include_str!("../tests/fixtures/expected/strings.json")).unwrap();
        for (input, want) in cases {
            let mut out = Vec::new();
            write_string(&mut out, &input);
            assert_eq!(String::from_utf8(out).unwrap(), want, "{input:?}");
        }
    }
}
