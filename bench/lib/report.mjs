// Markdown tables from a results JSON. Standalone: `node bench/lib/report.mjs results/latest.json`.

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const n0 = (x) => (x == null ? '–' : Math.round(x).toLocaleString('en-US'));
const ms = (x) => (x == null ? '–' : x < 1 ? x.toFixed(3) : x < 10 ? x.toFixed(2) : x < 100 ? x.toFixed(1) : x.toFixed(0));
const mib = (kib) => (kib == null ? '–' : (kib / 1024).toFixed(1));
const pct = (x) => (x == null ? '–' : `${x.toFixed(0)}%`);
const ratio = (a, b) => (a == null || b == null || b === 0 ? '–' : `${(a / b).toFixed(a / b >= 10 ? 0 : 1)}×`);
const spread = (s) => (s == null ? '' : ` ±${(s.spreadPct / 2).toFixed(0)}%`);

const dagger = (c) =>
  `${c?.mode?.startsWith('n=') ? ` (${c.mode})` : ''}${(c?.foreignCpuPct?.max ?? 0) > 150 ? ' ⚠' : ''}`;

const LABEL = { fastopm: 'fastopm', 'fastopm-1t': 'fastopm 1T', verdaccio: 'Verdaccio' };

function table(header, rows) {
  return [
    `| ${header.join(' | ')} |`,
    `|${header.map(() => '---').join('|')}|`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');
}

const keyOf = (c) => `${c.pkg}|${c.conns}`;

function comparison(cells, scenario, { withOneThread = false, mbps = false } = {}) {
  const sc = cells.filter((c) => c.scenario === scenario);
  if (!sc.length) return '';
  const by = {};
  for (const c of sc) (by[keyOf(c)] ??= {})[c.kind] = c;
  const header = ['package', 'c', 'RPS fastopm', 'RPS Verdaccio', 'ratio'];
  if (mbps) header.push('MB/s fastopm', 'MB/s Verdaccio');
  header.push('p50 ms f / V', 'p99 ms f / V', 'CPU f / V', 'req per CPU-s f / V');
  if (withOneThread) header.push('RPS fastopm 1T', '1T / V');
  const rows = Object.values(by).map((g) => {
    const f = g.fastopm;
    const v = g.verdaccio;
    const t = g['fastopm-1t'];
    const any = f ?? v ?? t;
    const row = [
      any.pkg,
      any.conns,
      f ? `${n0(f.rps.median)}${spread(f.rps)}${dagger(f)}` : '–',
      v ? `${n0(v.rps.median)}${spread(v.rps)}${dagger(v)}` : '–',
      ratio(f?.rps.median, v?.rps.median),
    ];
    if (mbps) row.push(n0(f?.mbps.median), n0(v?.mbps.median));
    row.push(
      `${ms(f?.p50.median)} / ${ms(v?.p50.median)}`,
      `${ms(f?.p99.median)} / ${ms(v?.p99.median)}`,
      `${pct(f?.cpuPct.median)} / ${pct(v?.cpuPct.median)}`,
      `${n0(f?.reqPerCpuSec?.median)} / ${n0(v?.reqPerCpuSec?.median)}`,
    );
    if (withOneThread) row.push(t ? `${n0(t.rps.median)}${spread(t.rps)}` : '–', ratio(t?.rps.median, v?.rps.median));
    return row;
  });
  return table(header, rows);
}

function bodySizes(cells, scenario) {
  const out = {};
  for (const c of cells.filter((x) => x.scenario === scenario))
    (out[c.pkg] ??= {})[c.kind] = c.sizePerRequest;
  return Object.entries(out)
    .map(([p, k]) => `${p}: fastopm ${n0(k.fastopm)} B, Verdaccio ${n0(k.verdaccio)} B`)
    .join('; ');
}

export function renderMarkdown(r) {
  const out = [];
  const m = r.meta;
  out.push(`<!-- generated by bench/lib/report.mjs from a results JSON -->`);
  out.push(`### Machine\n`);
  out.push(
    table(
      ['item', 'value'],
      [
        ['CPU', `${m.cpu}, ${m.cores} cores (${m.perfCores} performance + ${m.effCores} efficiency)`],
        ['RAM', `${m.memGiB.toFixed(0)} GiB`],
        ['OS', m.os],
        ['Node', m.node],
        ['Rust', m.rustc],
        ['load generator', m.oha],
        ['Verdaccio', m.verdaccio],
        ['fastopm binary', `${m.fastopmBinary} (built ${m.fastopmBuilt})`],
        ['date', m.date],
        [
          'options',
          `warm-up ${r.options.warmup}s, ${r.options.reps} × ${r.options.seconds}s per cell${r.options.quick ? ' (QUICK)' : ''}`,
        ],
      ],
    ),
  );

  const sections = [
    ['s1', 'S1 — abbreviated metadata (`Accept: install-v1`, `Accept-Encoding: gzip,deflate`), warm cache', { withOneThread: true }],
    ['s1i', 'S1i — abbreviated metadata without `Accept-Encoding` (no compression), warm cache, c=16', {}],
    ['s2', 'S2 — full metadata (`Accept: application/json`, gzip), warm cache', {}],
    ['s3', 'S3 — abbreviated metadata with matching `If-None-Match` (304), c=16', {}],
    ['s4', 'S4 — tarball from disk', { mbps: true }],
  ];
  for (const [id, title, opts] of sections) {
    const t = comparison(r.cells, id, opts);
    if (!t) continue;
    out.push(`\n### ${title}\n`);
    out.push(t);
    if (id !== 's4') out.push(`\nBytes per response (as sent): ${bodySizes(r.cells, id)}`);
  }

  if (r.cold?.length) {
    out.push(`\n### S5 — cold cache\n`);
    const rows = [];
    for (const c of r.cold) {
      for (const [what, list] of [
        ['same package × ' + r.options.herd + ' at once (metadata)', c.herdMeta],
        ['same tarball × ' + r.options.herd + ' at once (1 MiB)', c.herdTarball],
      ]) {
        const wall = list.map((x) => x.wallMs).sort((a, b) => a - b);
        const up = list.map((x) => x.uplinkRequests).join(', ');
        const p99 = list.map((x) => x.p99).sort((a, b) => a - b);
        const st = {};
        for (const x of list) for (const [k, v] of Object.entries(x.statuses)) st[k] = (st[k] ?? 0) + v;
        rows.push([
          LABEL[c.kind],
          what,
          ms(wall[wall.length >> 1]),
          ms(p99[p99.length >> 1]),
          up,
          JSON.stringify(st),
        ]);
      }
      for (const [what, x] of [
        [`${r.options.distinct} distinct packages, 1 client`, c.sequential],
        [`${r.options.distinct} distinct packages, 16 clients`, c.parallel],
      ]) {
        if (!x) continue;
        rows.push([LABEL[c.kind], what, ms(x.wallMs), `p50 ${ms(x.p50)} / p99 ${ms(x.p99)}`, x.uplinkRequests, JSON.stringify(x.statuses)]);
      }
    }
    out.push(table(['server', 'case', 'wall ms (median)', 'client latency ms', 'uplink requests (per rep)', 'statuses'], rows));
  }

  if (r.revalidate?.length) {
    out.push(`\n### S6 — \`maxage\` expired (every request revalidates, uplink answers 304)\n`);
    const by = {};
    for (const c of r.revalidate) (by[`${c.pkg}|${c.conns}|${c.uplinkDelayMs}`] ??= {})[c.kind] = c;
    const rows = Object.values(by).map((g) => {
      const f = g.fastopm;
      const v = g.verdaccio;
      const a = f ?? v;
      return [
        a.pkg,
        a.conns,
        a.uplinkDelayMs,
        `${n0(f?.rps.median)}${spread(f?.rps)}`,
        `${n0(v?.rps.median)}${spread(v?.rps)}`,
        ratio(f?.rps.median, v?.rps.median),
        `${ms(f?.p50.median)} / ${ms(v?.p50.median)}`,
        `${ms(f?.p99.median)} / ${ms(v?.p99.median)}`,
        `${f?.uplinkPerRequest?.median?.toFixed(3) ?? '–'} / ${v?.uplinkPerRequest?.median?.toFixed(3) ?? '–'}`,
        `${pct(f?.cpuPct.median)} / ${pct(v?.cpuPct.median)}`,
      ];
    });
    out.push(
      table(
        ['package', 'c', 'uplink delay ms', 'RPS fastopm', 'RPS Verdaccio', 'ratio', 'p50 ms f / V', 'p99 ms f / V', 'uplink req per client req f / V', 'CPU f / V'],
        rows,
      ),
    );
  }

  const res = r.resources ?? {};
  if (Object.keys(res).length) {
    out.push(`\n### S7 — resources\n`);
    const f = res.fastopm ?? {};
    const v = res.verdaccio ?? {};
    const peak = (kind, pkg, sc) =>
      r.cells.filter((c) => c.kind === kind && c.pkg === pkg && c.scenario === sc).reduce((a, c) => Math.max(a, c.peakRssKiB?.max ?? 0), 0) || null;
    const rows = [
      ['start-up to first `/-/ping` 200 (ms, median of runs)', ms(f.startupMs?.median), ms(v.startupMs?.median), ratio(v.startupMs?.median, f.startupMs?.median) + ' faster'],
      ['RSS idle, empty storage (MiB)', mib(f.idleRssEmptyKiB?.median), mib(v.idleRssEmptyKiB?.median), ratio(v.idleRssEmptyKiB?.median, f.idleRssEmptyKiB?.median) + ' smaller'],
      ['RSS idle after start, seeded storage (MiB)', mib(f.idleRssAfterStartKiB), mib(v.idleRssAfterStartKiB), ''],
      ['RSS peak under load, typescript abbreviated (S1) (MiB)', mib(peak('fastopm', 'typescript', 's1')), mib(peak('verdaccio', 'typescript', 's1')), ''],
      ['RSS peak under load, typescript full (S2) (MiB)', mib(peak('fastopm', 'typescript', 's2')), mib(peak('verdaccio', 'typescript', 's2')), ''],
      ['RSS peak under load, 50 MiB tarball (S4) (MiB)', mib(peak('fastopm', '50MiB', 's4')), mib(peak('verdaccio', '50MiB', 's4')), ''],
      ['RSS idle after the warm scenarios (MiB)', mib(f.idleRssAfterLoadKiB), mib(v.idleRssAfterLoadKiB), ''],
      ['uplink requests during all warm scenarios', f.uplinkRequestsDuringWarm ?? '–', v.uplinkRequestsDuringWarm ?? '–', ''],
    ];
    const fp = res.footprint;
    if (fp)
      rows.push([
        'on-disk size',
        `${(fp.fastopmBinaryBytes / 1e6).toFixed(1)} MB binary`,
        `${(fp.verdaccioNodeModulesBytes / 1e6).toFixed(0)} MB node_modules + ${(fp.nodeBinaryBytes / 1e6).toFixed(0)} MB node`,
        '',
      ]);
    out.push(table(['metric', 'fastopm', 'Verdaccio', ''], rows));
  }

  if (r.checks && Object.keys(r.checks).length) {
    out.push(`\n### Design checks — single client, \`typescript\` full manifest, no compression (ms, median)\n`);
    const rows = Object.entries(r.checks).map(([k, c]) => [
      LABEL[k],
      ms(c.hotMs.median),
      ms(c.newBaseMs.median),
      `${ms(c.fileChangedMs.median)} (change seen ${c.fileChangeSeen})`,
      ms(c.notModifiedMs.median),
      n0(c.bodyBytes),
    ]);
    out.push(table(['server', 'same request again', 'new Host each time', 'package.json changed before each', '304', 'body bytes'], rows));
  }

  if (r.notes?.length) {
    out.push(`\n### Notes from the run\n`);
    for (const n of r.notes) out.push(`- ${n}`);
  }
  return `${out.join('\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const file = process.argv[2];
  if (!file) {
    console.error('usage: node bench/lib/report.mjs <results.json>');
    process.exit(2);
  }
  process.stdout.write(renderMarkdown(JSON.parse(readFileSync(file, 'utf8'))));
}
