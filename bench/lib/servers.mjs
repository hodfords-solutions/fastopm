// mock uplink

export async function startUplink() {
  const child = track(
    spawn(process.execPath, [join(here, 'uplink.mjs'), '0'], { stdio: ['ignore', 'pipe', 'inherit'] }),
  );
  const port = await new Promise((res, rej) => {
    let buf = '';
    child.stdout.on('data', (d) => {
      buf += d;
      const nl = buf.indexOf('\n');
      if (nl >= 0) res(JSON.parse(buf.slice(0, nl)).port);
    });
    child.once('exit', (code) => rej(new Error(`uplink exited ${code}`)));
  });
  const origin = `http://127.0.0.1:${port}`;
  const admin = async (path, method = 'GET') => (await fetch(origin + path, { method })).json();
  return {
    origin,
    port,
    child,
    stats: () => admin('/__stats'),
    reset: () => admin('/__reset', 'POST'),
    setDelay: (ms) => admin(`/__config?delay=${ms}`, 'POST'),
    stop: () => stopChild(child),
  };
}

