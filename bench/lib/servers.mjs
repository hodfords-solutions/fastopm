export function fastopmBin() {
  return join(BENCH_DIR, 'target', 'release', 'fastopm');
}

export function verdaccioBin() {
  const candidates = [
    join(BENCH_DIR, 'node_modules', 'verdaccio', 'bin', 'verdaccio'),
    join(ROOT_DIR, 'compat', 'node_modules', 'verdaccio', 'bin', 'verdaccio'),
  ];
  const found = candidates.find((c) => existsSync(c));
  if (!found) throw new Error(`verdaccio not found in ${candidates.join(' or ')}`);
  return found;
}

/** Kinds of server the benchmark knows. `fastopm-1t` = fastopm with one Tokio worker thread. */
export const KINDS = {
  fastopm: { label: 'fastopm' },
  'fastopm-1t': { label: 'fastopm (1 worker thread)' },
  verdaccio: { label: 'verdaccio 7.1.0' },
};

/**
 * Start a server in `dir` (config.yaml written there) and wait for `/-/ping` 200.
 * Returns {kind, port, url, pid, startupMs, stop()}.
 */
export async function startServer(kind, { dir, storage, uplink, maxage, logs = false }) {
  mkdirSync(dir, { recursive: true });
  const configPath = join(dir, 'config.yaml');
  writeFileSync(configPath, configYaml({ storage, uplink, maxage }));
  const port = await freePort();
  const listen = `127.0.0.1:${port}`;
  const out = logs ? openSync(join(dir, 'server.log'), 'a') : 'ignore';
  const stdio = ['ignore', out, out];
  let child;
  const t0 = performance.now();
  if (kind === 'verdaccio') {
    child = spawn(process.execPath, [verdaccioBin(), '--config', configPath, '--listen', listen], {
      cwd: dir,
      stdio,
      env: { ...process.env, NODE_ENV: 'production' },
    });
  } else {
    const env = { ...process.env };
    delete env.RUST_LOG;
    if (kind === 'fastopm-1t') env.TOKIO_WORKER_THREADS = '1';
    child = spawn(fastopmBin(), ['--config', configPath, '--listen', listen], { cwd: dir, stdio, env });
  }
  track(child);
  let exited = null;
  child.once('exit', (code, signal) => {
    exited = { code, signal };
  });
  const url = `http://${listen}`;
  for (;;) {
    if (exited) throw new Error(`${kind} exited during start-up: ${JSON.stringify(exited)}`);
    try {
      const r = await fetch(`${url}/-/ping`);
      await r.arrayBuffer();
      if (r.status === 200) break;
    } catch {}
    if (performance.now() - t0 > 60_000) throw new Error(`${kind} did not answer /-/ping in 60 s`);
    await sleep(5);
  }
  const startupMs = performance.now() - t0;
  return { kind, port, url, pid: child.pid, child, startupMs, dir, stop: () => stopChild(child) };
}

export async function stopChild(child) {
  if (child.exitCode !== null || child.signalCode !== null) return;
  const done = new Promise((r) => child.once('exit', r));
  child.kill('SIGTERM');
  const t = setTimeout(() => child.kill('SIGKILL'), 5000);
  await done;
  clearTimeout(t);
}

