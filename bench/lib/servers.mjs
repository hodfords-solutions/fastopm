// process metrics (macOS / BSD ps)

/** {rssKiB, cpuSec} of a pid. `ps -o time` is user+system CPU time. */
export async function procStats(pid) {
  const { stdout } = await execFileP('ps', ['-o', 'rss=,time=', '-p', String(pid)]);
  const [rss, time] = stdout.trim().split(/\s+/);
  return { rssKiB: Number(rss), cpuSec: parseCpuTime(time) };
}

function parseCpuTime(t) {
  // [[dd-]hh:]mm:ss.cc
  let days = 0;
  if (t.includes('-')) {
    const [d, rest] = t.split('-');
    days = Number(d);
    t = rest;
  }
  const parts = t.split(':').map(Number);
  let sec = 0;
  for (const p of parts) sec = sec * 60 + p;
  return days * 86400 + sec;
}

/**
 * CPU (% of one core, summed) used by processes that are not part of the benchmark: not this
 * runner, not its children (servers, mock uplink), not oha / ps. macOS `ps` %cpu is a decaying
 * average, so this is an indication, not an exact figure.
 */
export async function foreignCpu() {
  const own = new Set([process.pid, ...[...children].map((c) => c.pid)]);
  const { stdout } = await execFileP('ps', ['-A', '-o', 'pid=,pcpu=,comm=']);
  let sum = 0;
  for (const line of stdout.split('\n')) {
    const m = line.trim().match(/^(\d+)\s+([\d.]+)\s+(.*)$/);
    if (!m || own.has(Number(m[1]))) continue;
    if (/(^|\/)(oha|ps)$/.test(m[3])) continue;
    sum += Number(m[2]);
  }
  return sum;
}

/**
 * Wait until foreign CPU stays under `limit` for two consecutive 1 s samples (other work on the
 * machine would skew the run). Returns {waitedMs, foreign} — `foreign` is the last sample.
 */
export async function waitQuiet(limit = 150, maxMs = 180_000) {
  const t0 = performance.now();
  let ok = 0;
  let last = 0;
  while (performance.now() - t0 < maxMs) {
    last = await foreignCpu();
    ok = last < limit ? ok + 1 : 0;
    if (ok >= 2) break;
    await sleep(1000);
  }
  return { waitedMs: performance.now() - t0, foreign: last };
}

/** Sample foreign CPU every second until stopped; returns the mean. */
export function foreignSampler(everyMs = 1000) {
  const xs = [];
  let running = true;
  const loop = (async () => {
    while (running) {
      try {
        xs.push(await foreignCpu());
      } catch {}
      await sleep(everyMs);
    }
  })();
  return {
    async stop() {
      running = false;
      await loop;
      return xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : null;
    },
  };
}

/** Sample RSS every `everyMs` until stopped; returns {peakRssKiB, samples}. */
export function rssSampler(pid, everyMs = 100) {
  let peak = 0;
  let samples = 0;
  let running = true;
  const loop = (async () => {
    while (running) {
      try {
        const { rssKiB } = await procStats(pid);
        if (rssKiB > peak) peak = rssKiB;
        samples += 1;
      } catch {}
      await sleep(everyMs);
    }
  })();
  return {
    async stop() {
      running = false;
      await loop;
      return { peakRssKiB: peak, samples };
    },
  };
}
